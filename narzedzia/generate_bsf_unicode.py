#!/usr/bin/env python3
"""Generate native Unicode 15.1.0 properties from checked-in Unicode UCD files."""
from pathlib import Path
import hashlib
root=Path(__file__).resolve().parents[1];src=root/'narzedzia/unicode/15.1.0'
props=['Other','CR','LF','Control','Extend','ZWJ','Regional_Indicator','Prepend','SpacingMark','L','V','T','LV','LVT']
def read(name,kind):
 out=[]
 for line in (src/name).read_text().splitlines():
  fields=[x.strip() for x in line.split('#')[0].split(';')]
  if len(fields)<2 or not fields[0]:continue
  value=kind(fields)
  if value is None:continue
  r=fields[0].split('..');out.append((int(r[0],16),int(r[-1],16),value))
 return sorted(out)
sets={
 'gcb':read('GraphemeBreakProperty.txt',lambda f:props.index(f[1]) if f[1] not in ('LV','LVT') else None),
 'ep':read('emoji-data.txt',lambda f:1 if f[1]=='Extended_Pictographic' else None),
 'incb':read('DerivedCoreProperties.txt',lambda f:['None','Consonant','Extend','Linker'].index(f[2]) if f[1]=='InCB' else None),
 'ignorable':read('DerivedCoreProperties.txt',lambda f:1 if f[1]=='Default_Ignorable_Code_Point' else None),
}
ccc=[]
for line in (src/'UnicodeData.txt').read_text().splitlines():
 f=line.split(';');cp=int(f[0],16);v=int(f[3])
 if v:
  if ccc and ccc[-1][1]+1==cp and ccc[-1][2]==v:ccc[-1]=(ccc[-1][0],cp,v)
  else:ccc.append((cp,cp,v))
sets['ccc']=ccc
s='// Generated by narzedzia/generate_bsf_unicode.py; Unicode 15.1.0.\n// Unicode data license: narzedzia/unicode/LICENSE.txt\n'
for name,rows in sets.items():
 merged=[]
 for a,b,v in rows:
  if merged and merged[-1][1]+1==a and merged[-1][2]==v:merged[-1]=(merged[-1][0],b,v)
  else:merged.append((a,b,v))
 rows=merged
 data=[]
 for a,b,v in rows:data += [a&255,(a>>8)&255,a>>16,b&255,(b>>8)&255,b>>16,v]
 s+=f'static const uint8_t unicode_{name}[] = {{\n'
 for i in range(0,len(data),28):s+=','.join(map(str,data[i:i+28]))+',\n'
 s+='};\n'
 print(name,len(rows),len(data),'bytes')
(root/'bsf/unicode_data.inc').write_text(s)
manifest={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(src.iterdir())}
import json
(src/'SHA256.json').write_text(json.dumps({k:v for k,v in manifest.items() if k!='SHA256.json'},indent=2)+'\n')
