def parse(spec):
    path, index, axes = spec, 0, {}
    if '@' in path:
        path, a = path.split('@', 1)
        for kv in a.split(','):
            k, v = kv.split('=')
            axes[k] = float(v)
    if '#' in path:
        path, i = path.split('#', 1)
        index = int(i)
    return root / path, index, axes

def shape(spec, script, direction, text, features=''):
    path, index, axes = parse(spec)
    face = hb.Face(hb.Blob.from_file_path(str(path)), index)
    font = hb.Font(face)
    font.scale = (face.upem, face.upem)
    if axes:
        font.set_variations(axes)
    buf = hb.Buffer()
    buf.add_utf8(text.encode("utf-8"))
    buf.direction = direction
    buf.script = script
    buf.language = 'und'
    feats = {}
    for tag in filter(None, features.split(',')):
        feats[tag] = True
    hb.shape(font, buf, feats)
    return text.encode('utf-8'), [(i.codepoint, i.cluster, p.x_advance, p.y_advance,
                                   p.x_offset, p.y_offset)
                                  for i, p in zip(buf.glyph_infos, buf.glyph_positions)]

def main(cases, target):
    out = ['# Generated by narzedzia/bsf22/generate_shaping_oracle.py '
           f'(uharfbuzz {hb.__version__}, HarfBuzz {hb.version_string()})']
    for case in cases:
        name, spec, script, direction, texts = case[:5]
        features = case[5] if len(case) > 5 else ''
        for text in texts:
            data, glyphs = shape(spec, script, direction, text, features)
            rec = ';'.join(','.join(str(v) for v in g) for g in glyphs)
            row = [name, spec, script, direction, data.hex(), rec]
            if features:
                row.append(features)
            out.append('\t'.join(row))
    target.write_text('\n'.join(out) + '\n')
    print(f'{len(out) - 1} oracle rows -> {target}')

